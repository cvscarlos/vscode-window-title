import { createHash } from 'node:crypto';
import type { HudFontFamily, HudPosition, PillPosition } from '../configuration/settings';

export const CSS_FILE_NAME = 'nt-window-title.css';
export const SCRIPT_FILE_NAME = 'nt-window-title.js';

const OVERLAY_ID = 'nt-window-title-hud';
const VISIBLE_CLASS = 'nt-window-title-hud-visible';
const PILL_ID = 'nt-window-title-pill';

/** Bounded wait for the extension host to publish the status-bar badge. */
const READY_ATTEMPTS = 12;
const READY_INTERVAL_MILLISECONDS = 300;

export interface HudAssetConfig {
	/** False when only the title-bar pill is wanted. */
	hudEnabled: boolean;
	displayMilliseconds: number;
	minIntervalMilliseconds: number;
	position: HudPosition;
	fontSizePixels: number;
	uppercase: boolean;
	/** A CSS-ready color (hex or `var(--vscode-…)`), or '' for the theme foreground. */
	color: string;
	fontFamily: HudFontFamily;
	showOnWindowOpen: boolean;
	pill: PillAssetConfig;
}

export interface PillAssetConfig {
	enabled: boolean;
	position: PillPosition;
	/** A validated hex background, or '' to use the theme's button colors. */
	color: string;
	/** Derived from `color` — never configured, so it cannot be unreadable. */
	textColor: string;
	uppercase: boolean;
	fontFamily: HudFontFamily;
	bordered: boolean;
}

export interface HudAssets {
	css: string;
	script: string;
	/** Identifies this exact pair of assets, so a stale patch is detectable. */
	hash: string;
}

function restingTransform(position: HudPosition): string {
	return position === 'top'
		? 'translate(-50%, 0) scale(0.94)'
		: 'translate(-50%, -50%) scale(0.94)';
}

function visibleTransform(position: HudPosition): string {
	return position === 'top' ? 'translate(-50%, 0) scale(1)' : 'translate(-50%, -50%) scale(1)';
}

/**
 * `--vscode-font-family` does not exist as a custom property (verified empty in
 * 1.130, even on `.monaco-workbench`). Since the overlay is mounted inside the
 * workbench, `inherit` picks up the real UI font instead. The mono stack is
 * explicit for the same reason — there is no editor-font variable to read.
 */
function fontStack(family: HudFontFamily): string {
	return family === 'mono'
		? 'ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, "Courier New", monospace'
		: 'inherit';
}

function buildHudCss(config: HudAssetConfig): string {
	const color = config.color === '' ? 'var(--vscode-foreground, #CCCCCC)' : config.color;
	const verticalAnchor = config.position === 'top' ? 'top: 11vh;' : 'top: 50%;';
	const textTransform = config.uppercase ? 'uppercase' : 'none';

	return `/* Generated by the Window Title nt extension. Edits here are overwritten. */
#${OVERLAY_ID} {
	position: fixed;
	left: 50%;
	${verticalAnchor}
	z-index: 2147483000;
	box-sizing: border-box;
	max-width: 76vw;
	padding: 18px 34px;
	border: 1px solid var(--vscode-widget-border, rgba(128, 128, 128, 0.35));
	border-radius: 16px;
	background: var(--vscode-editorWidget-background, rgba(30, 30, 30, 0.92));
	color: ${color};
	box-shadow: 0 18px 52px rgba(0, 0, 0, 0.42);
	font-family: ${fontStack(config.fontFamily)};
	font-size: ${config.fontSizePixels}px;
	font-weight: 600;
	letter-spacing: 0.02em;
	line-height: 1.15;
	text-align: center;
	text-transform: ${textTransform};
	white-space: nowrap;
	overflow: hidden;
	text-overflow: ellipsis;
	opacity: 0;
	transform: ${restingTransform(config.position)};
	pointer-events: none;
	user-select: none;
	transition:
		opacity 140ms ease,
		transform 140ms ease;
}

#${OVERLAY_ID}.${VISIBLE_CLASS} {
	opacity: 1;
	transform: ${visibleTransform(config.position)};
}

@media (prefers-reduced-motion: reduce) {
	#${OVERLAY_ID} {
		transform: ${visibleTransform(config.position)};
		transition: opacity 80ms linear;
	}

	#${OVERLAY_ID}.${VISIBLE_CLASS} {
		transform: ${visibleTransform(config.position)};
	}
}
${buildPillCss(config.pill)}`;
}

/**
 * Reproduces VS Code's own "Update" pill rule for rule, so the two are
 * indistinguishable and both follow the active theme.
 *
 * Source of truth: `.update-indicator` and `.update-indicator.prominent` in
 * `vs/workbench/contrib/update/browser/media/updateTitleBarEntry.css`. The
 * "Sign in" pill is the same treatment (`chatSetupContributions.ts` registers it
 * on the same menu, at "the same position as the update button").
 *
 * The theme tokens matter: hardcoding 6px and 12px here would drift the moment
 * VS Code retunes its corner-radius or font scale.
 */
function buildPillCss(pill: PillAssetConfig): string {
	if (!pill.enabled) {
		return '';
	}

	const background = pill.color === '' ? 'var(--vscode-button-background, #0078D4)' : pill.color;
	const foreground =
		pill.color === '' ? 'var(--vscode-button-foreground, #FFFFFF)' : pill.textColor;

	// VS Code's own pill borders in its background color, so the border is
	// invisible. That breaks down when the title bar happens to be the same color
	// as the pill — the pill then vanishes into it. Bordering in the *text* color
	// fixes it for free: that color is already guaranteed to contrast with the
	// fill, so it necessarily contrasts with a title bar of the same color too.
	const borderColor = pill.bordered ? foreground : background;

	// macOS draws the window buttons over the leading edge of the title bar, and
	// `.titlebar-left` is empty there, so a left-aligned pill starts at x≈4 and
	// sits underneath them. The traffic lights are drawn by the OS, outside the
	// DOM, so their extent cannot be measured — this clears the conventional
	// ~70px they occupy. Only emitted for the left position, and scoped to the
	// `mac` class VS Code puts on `.monaco-workbench`.
	const macTrafficLightInset =
		pill.position === 'left'
			? `
.mac #${PILL_ID} {
	margin-left: 80px;
}
`
			: '';

	return `
#${PILL_ID} {
	display: flex;
	align-items: center;
	flex: 0 0 auto;
	/* The host container is taller than the title bar and starts above it, so
	   without this the pill anchors to the container's top edge and is clipped. */
	align-self: center;
	box-sizing: border-box;
	height: 22px;
	max-width: 30vw;
	margin: 0 4px;
	padding: 0 8px;
	border: 1px solid ${borderColor};
	border-radius: var(--vscode-cornerRadius-medium, 6px);
	background-color: ${background};
	color: ${foreground};
	/* inherit resolves to the workbench UI font (var(--vscode-font-family) does
	   not exist); mono ships an explicit stack. */
	font-family: ${fontStack(pill.fontFamily)};
	font-size: var(--vscode-bodyFontSize-small, 12px);
	white-space: nowrap;
	overflow: hidden;
	text-overflow: ellipsis;
	text-transform: ${pill.uppercase ? 'uppercase' : 'none'};
	/* Never intercept clicks or the window-drag region. */
	pointer-events: none;
	user-select: none;
}
${macTrafficLightInset}`;
}

function buildHudScript(config: HudAssetConfig): string {
	// Baked in as a literal because the renderer cannot read files or use the
	// network: the workbench CSP is `default-src 'none'` with `connect-src` limited
	// to self/https/ws.
	const baked = JSON.stringify(
		{
			hudEnabled: config.hudEnabled,
			displayMs: config.displayMilliseconds,
			minIntervalMs: config.minIntervalMilliseconds,
			showOnWindowOpen: config.showOnWindowOpen,
			readyAttempts: READY_ATTEMPTS,
			readyIntervalMs: READY_INTERVAL_MILLISECONDS,
			pillEnabled: config.pill.enabled,
			pillPosition: config.pill.position,
		},
		undefined,
		'\t'
	);

	return `// Generated by the Window Title nt extension. Edits here are overwritten.
//
// Announces the project name over the middle of the window when it gains focus.
// Constraints this file works within, all imposed by the workbench page:
//   * CSP forbids inline script, so this ships as its own same-origin file.
//   * CSP forbids network and file reads, so all configuration is baked in above.
//   * Trusted Types are required, so the DOM is built with createElement and
//     textContent only - never innerHTML.
// At rest this costs one focus listener; a timer exists only while the HUD is
// on screen.

const CONFIG = ${baked};

const OVERLAY_ID = '${OVERLAY_ID}';
const VISIBLE_CLASS = '${VISIBLE_CLASS}';
const PILL_ID = '${PILL_ID}';

// Must match src/hud/markers.ts: the status-bar badge wraps the project name in
// these two invisible format characters so it can be read back exactly.
const NAME_OPEN = String.fromCodePoint(0x2062);
const NAME_CLOSE = String.fromCodePoint(0x2063);
const NOISE = new RegExp(
	'[' + NAME_OPEN + NAME_CLOSE + String.fromCodePoint(0xe000) + '-' + String.fromCodePoint(0xf8ff) + ']',
	'gu'
);

function clean(text) {
	return text.replace(NOISE, '').trim();
}

/** The authoritative source: the name the extension host actually resolved. */
function fromStatusBar() {
	const items = document.querySelectorAll('.statusbar-item');
	for (const item of items) {
		const text = item.textContent || '';
		const start = text.indexOf(NAME_OPEN);
		if (start === -1) {
			continue;
		}
		const end = text.indexOf(NAME_CLOSE, start + 1);
		if (end === -1) {
			continue;
		}
		const name = clean(text.slice(start + 1, end));
		if (name) {
			return name;
		}
	}
	return '';
}

/** Halves a string that is exactly itself twice. Mirrors undoubleText in markers.ts. */
function undouble(text) {
	const half = text.length / 2;
	if (half > 0 && Number.isSafeInteger(half) && text.slice(0, half) === text.slice(half)) {
		return text.slice(0, half);
	}
	return text;
}

/**
 * Fallback for when the badge is switched off.
 *
 * The title bar renders the window title MORE THAN ONCE: with the Command Center
 * enabled, VS Code 1.130 keeps a visible label plus hidden ones (.search-label
 * and friends) inside .window-title, so textContent yields the name repeated.
 * Take the first text node whose parent is actually laid out instead, which does
 * not depend on Monaco's internal class names.
 */
function fromTitleBar() {
	const root =
		document.querySelector('.titlebar-center .window-title') ||
		document.querySelector('.window-title');
	if (!root) {
		return '';
	}

	const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
	let node = walker.nextNode();
	while (node) {
		const parent = node.parentElement;
		if (parent && (parent.offsetWidth || parent.offsetHeight)) {
			const visible = clean(node.nodeValue || '');
			if (visible) {
				return visible;
			}
		}
		node = walker.nextNode();
	}

	// Nothing measurable (a hidden title bar): undouble as a last resort.
	return undouble(clean(root.textContent || ''));
}

function resolveName() {
	return fromStatusBar() || fromTitleBar() || clean(document.title);
}

/**
 * Where the pill goes. Never inside .window-title — fromTitleBar() reads that
 * subtree, and the pill must not become its own name source.
 *
 * 'right' targets .titlebar-right, which is the flex row (align-items: center)
 * holding the window controls and the .center-adjacent-toolbar-container that
 * carries the built-in Update and Sign in pills — so prepending here puts ours
 * immediately beside them, correctly centered.
 *
 * Do NOT insert into .center-adjacent-toolbar-container itself, tempting as it
 * looks: it is display:block, 44px tall and starts 8px above the title bar, so a
 * child anchors to that box and gets clipped off the top of the window.
 */
function pillParent() {
	const container =
		document.querySelector('.part.titlebar .titlebar-container') ||
		document.querySelector('.part.titlebar');
	if (!container) {
		return null;
	}
	const side =
		CONFIG.pillPosition === 'left'
			? '.titlebar-left'
			: CONFIG.pillPosition === 'center'
				? '.titlebar-center'
				: '.titlebar-right';
	return container.querySelector(side) || container;
}

function installPill() {
	let pill = null;
	let observed = null;
	const observer = new MutationObserver(function () {
		render();
	});

	function render() {
		const parent = pillParent();
		if (!parent) {
			return;
		}

		// Attach here rather than once at startup: this file is evaluated while the
		// page body is still empty, so the title bar does not exist yet and an
		// observer set up then would never attach at all. Re-observing on a changed
		// parent also survives VS Code replacing the row wholesale.
		if (observed !== parent) {
			observer.disconnect();
			observer.observe(parent, { childList: true });
			observed = parent;
		}
		const name = resolveName();
		if (!name) {
			return;
		}
		if (!pill) {
			pill = document.createElement('div');
			pill.id = PILL_ID;
			// Decorative: the name is already the window title.
			pill.setAttribute('aria-hidden', 'true');
		}
		// Setting textContent mutates the pill, not the observed parent, so this
		// cannot re-trigger the observer below.
		if (pill.textContent !== name) {
			pill.textContent = name;
		}
		if (pill.parentElement !== parent) {
			if (CONFIG.pillPosition === 'right') {
				parent.prepend(pill);
			} else {
				parent.append(pill);
			}
		}
	}

	render();
	return render;
}

function install() {
	let overlay = null;
	let hideTimer = 0;
	let lastShownAt = 0;

	function ensureOverlay() {
		// MUST be inside .monaco-workbench, not document.body. Every --vscode-*
		// custom property is defined on that element, and the workbench UI font is
		// set there too. On document.body they all resolve to nothing and the
		// overlay inherits Times 11px from the browser default.
		const host = document.querySelector('.monaco-workbench') || document.body;

		if (!overlay) {
			overlay = document.createElement('div');
			overlay.id = OVERLAY_ID;
			// Decorative: the name is already in the title bar and the status bar.
			overlay.setAttribute('aria-hidden', 'true');
		}

		// Re-home every time, not just on creation: an announcement can land before
		// the workbench element exists, and an overlay parked on document.body would
		// otherwise stay there — themed with nothing — for the rest of the session.
		if (overlay.parentElement !== host) {
			host.appendChild(overlay);
		}
		return overlay;
	}

	function show() {
		if (!document.body) {
			return;
		}
		const now = Date.now();
		if (now - lastShownAt < CONFIG.minIntervalMs) {
			return;
		}
		const name = resolveName();
		if (!name) {
			return;
		}
		lastShownAt = now;

		const element = ensureOverlay();
		element.textContent = name;
		element.classList.remove(VISIBLE_CLASS);
		// Force a reflow so a repeated announcement replays the transition.
		void element.offsetWidth;
		element.classList.add(VISIBLE_CLASS);

		if (hideTimer) {
			clearTimeout(hideTimer);
		}
		hideTimer = setTimeout(function () {
			hideTimer = 0;
			element.classList.remove(VISIBLE_CLASS);
		}, CONFIG.displayMs);
	}

	const renderPill = CONFIG.pillEnabled ? installPill() : null;

	window.addEventListener('focus', function () {
		if (!document.hasFocus()) {
			return;
		}
		// Cheap re-assertion: catches a name change without watching for one.
		if (renderPill) {
			renderPill();
		}
		if (CONFIG.hudEnabled) {
			show();
		}
	});

	// The badge is published by the extension host after we load, so the first
	// read has to wait for it. Bounded — it gives up rather than spinning.
	let attempts = 0;
	function whenReady() {
		attempts += 1;
		if (!fromStatusBar() && attempts < CONFIG.readyAttempts) {
			setTimeout(whenReady, CONFIG.readyIntervalMs);
			return;
		}
		if (renderPill) {
			renderPill();
		}
		// A freshly opened window is already focused, so no focus event arrives.
		if (CONFIG.hudEnabled && CONFIG.showOnWindowOpen && document.hasFocus()) {
			show();
		}
	}
	setTimeout(whenReady, CONFIG.readyIntervalMs);
}

// A duplicated script tag must not mean two focus listeners.
if (!globalThis.__ntWindowTitleHudInstalled) {
	globalThis.__ntWindowTitleHudInstalled = true;
	install();
}
`;
}

export function buildHudAssets(config: HudAssetConfig): HudAssets {
	const css = buildHudCss(config);
	const script = buildHudScript(config);
	const hash = createHash('sha256').update(css).update(script).digest('hex').slice(0, 12);
	return { css, script, hash };
}
